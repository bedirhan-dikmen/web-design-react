/**
 * Measured geometry for the 3D hero product scene.
 *
 * ## Unit system
 *
 * 1 world unit = 100 px of `image.png` (1045x803), the approved composite for
 * this cluster. The counter's top surface is the y=0 plane, so every object's
 * "sits on the counter" condition is literally `bottom === 0`. The scene box
 * measured off image.png is x 35..1015 px, so world x is
 * `(imagePx - 35) / 100 - SCENE_CENTRE_X`, which centres the composition on
 * the origin.
 *
 * ## What is measured and what is derived
 *
 * Body widths, x positions and Y rotations are measured from image.png with a
 * 25px grid overlaid. Screen *heights* are never measured — they are derived
 * from the real texture aspect ratio, because the screenshots are used at their
 * true proportions and are never stretched or cropped (docs/IMAGE_PIPELINE.md).
 * Where our asset is shaped differently from the reference hardware, the object
 * matches the reference's width and contact point and its height falls where
 * the asset puts it. See docs/ASSET_MANIFEST.md.
 *
 * ## Rotation sign convention
 *
 * three.js `rotation.y` is counter-clockwise seen from above, so a *positive*
 * value turns an object's right edge away from the camera — the same sense as
 * CSS `rotateY`. Objects left of centre therefore take positive values (they
 * face inward, to the right) and objects right of centre take negative ones.
 * The magnitudes come from comparing each device's left and right edge heights
 * in image.png: the taller edge is the nearer one.
 *
 * `rotation.x` is negative for a natural backward lean (top edge away).
 */

const DEG = Math.PI / 180;

/** Centre of the measured scene box, in world units before centring. */
const SCENE_CENTRE_X = 4.9;

/** image.png x pixel -> centred world x, valid in the z = 0 plane. */
const x = (imagePx: number) => imagePx / 100 - 0.35 - SCENE_CENTRE_X;

/**
 * Perspective correction for an object standing at depth z.
 *
 * "1 unit = 100 px" only holds in the z = 0 plane, ~22.6 units from the
 * camera. An object placed further back projects smaller, so a width measured
 * on the reference has to be scaled up by its distance ratio to land at the
 * measured size — and likewise its x offset from the view centre. Without
 * this the rear monitor, at z = -2.4, rendered ~10% narrower than measured.
 */
const CAMERA_DISTANCE = 22.6;
const depth = (z: number) => (CAMERA_DISTANCE - z) / CAMERA_DISTANCE;
/** Measured width at depth z. */
const w = (units: number, z: number) => units * depth(z);
/** Measured x at depth z. */
const xz = (imagePx: number, z: number) => x(imagePx) * depth(z);

