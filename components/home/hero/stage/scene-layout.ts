export type DeviceSpec = {
  /** Outer shell width in world units. */
  bodyWidth: number;
  /** Bezel thickness on the left and right of the screen. */
  side: number;
  /** Bezel above the screen. */
  top: number;
  /** Bezel below the screen — the chin. */
  chin: number;
  /** Shell thickness front to back. */
  depth: number;
  /** Texture aspect (w/h); the screen height is derived from it. */
  aspect: number;
  /**
   * Where the object touches the counter. Y is always 0 — that is the whole
   * point of putting the counter's surface on the y = 0 plane, and it means
   * "this device stands on the counter" is structural rather than a number
   * each device has to get right on its own.
   */
  position: [number, number, number];
  /**
   * How far the stand raises the shell above the counter. The shell is placed
   * at `lift + bodyHeight/2`, and the stand geometry fills 0..lift underneath
   * it. Zero for objects that sit directly on the stone, like the phone.
   */
  lift: number;
  rotation: [number, number, number];
  /**
   * Corner radius of the visible screen, as a fraction of the screen's
   * shorter side. Real panels are never square-cornered; a hard 90-degree
   * screenshot corner is one of the quickest tells of a pasted-on image.
   */
  screenRadius?: number;
  /**
   * Black glass border between the shell and the live pixels. On the monitor
   * this is what separates the silver frame from the UI, as in image.png.
   */
  glassBorder?: number;
};

/** Screen width implied by a spec. */
export const screenWidth = (d: DeviceSpec) => d.bodyWidth - 2 * d.side;
/** Screen height implied by a spec and its texture's true aspect. */
export const screenHeight = (d: DeviceSpec) => screenWidth(d) / d.aspect;
/** Total shell height implied by a spec. */
export const bodyHeight = (d: DeviceSpec) =>
  d.top + screenHeight(d) + d.chin;

